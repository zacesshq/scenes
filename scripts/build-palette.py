#!/usr/bin/env python3
"""Writes src/palette.rs from palette/zacess.json.

The JSON file is a copy of the palette in zacesshq/themes, the one place every Zacess colour is
defined. Run this after updating the copy and commit both files. CI fails when the generated table
is out of date.

Usage: python3 scripts/build-palette.py [palette.json] [palette.rs]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "palette" / "zacess.json"
TARGET = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src" / "palette.rs"

UI_TOKENS = ["background", "foreground", "muted", "accent", "link", "cursor", "error", "warning", "info"]
SYNTAX_TOKENS = ["keyword", "control", "function", "type", "string", "number", "comment", "property", "regex"]


def rgb(value: str) -> str:
    value = value.lstrip("#").lower()
    if len(value) != 6 or any(c not in "0123456789abcdef" for c in value):
        raise SystemExit(f"not a six digit hex colour: {value}")
    return f"Rgb::from_hex(0x{value})"


def main() -> None:
    palette = json.loads(SOURCE.read_text())
    themes = palette["themes"]
    if len(themes) != 8:
        raise SystemExit(f"expected eight themes, found {len(themes)}")
    out = [
        "// generated by scripts/build-palette.py from palette/zacess.json, never edited by hand",
        "",
        "use crate::colour::Rgb;",
        "",
        "/// The version of the Zacess palette these colours come from.",
        f'pub const PALETTE_VERSION: &str = "{palette["version"]}";',
        "",
        "/// One Zacess theme: the interface and terminal colours a scene can draw with.",
        "#[derive(Debug)]",
        "pub struct ThemeData {",
        "    /// The id the palette and the theme state file use, such as `deep-contrast-dark`.",
        "    pub id: &'static str,",
        "    /// The full name, such as `Zacess Deep Contrast Dark`.",
        "    pub name: &'static str,",
        "    /// True for a dark background.",
        "    pub dark: bool,",
        "    pub background: Rgb,",
        "    pub foreground: Rgb,",
        "    pub muted: Rgb,",
        "    pub accent: Rgb,",
        "    pub link: Rgb,",
        "    pub cursor: Rgb,",
        "    pub error: Rgb,",
        "    pub warning: Rgb,",
        "    pub info: Rgb,",
        "    /// Syntax colours in the order keyword, control, function, type, string, number, comment,",
        "    /// property and regex.",
        "    pub syntax: [Rgb; 9],",
        "    /// The sixteen terminal colours in ANSI order.",
        "    pub ansi: [Rgb; 16],",
        "}",
        "",
        "/// Every Zacess theme, in the palette's order.",
        "pub const THEMES: [ThemeData; 8] = [",
    ]
    for theme in themes:
        ui = theme["ui"]
        syntax = theme["syntax"]
        ansi = theme["terminal"]["ansi"]
        if len(ansi) != 16:
            raise SystemExit(f"{theme['id']} has {len(ansi)} terminal colours")
        out.append("    ThemeData {")
        out.append(f'        id: "{theme["id"]}",')
        out.append(f'        name: "{theme["name"]}",')
        out.append(f"        dark: {'true' if theme['appearance'] == 'dark' else 'false'},")
        for token in UI_TOKENS:
            out.append(f"        {token}: {rgb(ui[token])},")
        out.append("        syntax: [")
        for token in SYNTAX_TOKENS:
            out.append(f"            {rgb(syntax[token])},")
        out.append("        ],")
        out.append("        ansi: [")
        for value in ansi:
            out.append(f"            {rgb(value)},")
        out.append("        ],")
        out.append("    },")
    out.append("];")
    TARGET.write_text("\n".join(out) + "\n")
    print(f"wrote {TARGET} from {SOURCE.name} ({palette['version']})")


if __name__ == "__main__":
    main()
